/*
  The icon for the form a medication comes in, by the names of its SNOMED basic dose form
  (e.g. "Tablet", "Suspension") and intended site (e.g. "Oral", "Parenteral"). The route is
  looked at first: a powder or solution given parenterally is an injection, not a bottle.
  There are only a handful of icons, so forms without a fitting one (creams, patches,
  suppositories...) have none and are shown by name instead.
*/
export function medicationFormIcon(
  { form, route }: { form: string | null; route: string | null },
): ((props: IconProps) => JSX.Element) | null {
  const route_name = route?.toLowerCase() ?? ''
  if (route_name === 'parenteral' || route_name.startsWith('intra') || route_name === 'subcutaneous') return SyringeIcon
  if (route_name === 'pulmonary' || route_name === 'endotracheopulmonary') return InhalerIcon

  const form_name = form?.toLowerCase() ?? ''
  if (['tablet', 'lozenge', 'pastille', 'pill'].some((solid) => form_name.includes(solid))) return TabletIcon
  if (form_name.includes('capsule') || form_name === 'cachet') return CapsuleIcon
  if (['solution', 'suspension', 'syrup', 'elixir', 'emulsion', 'tincture', 'pure liquid'].includes(form_name)) return BottleIcon
  return null
}
